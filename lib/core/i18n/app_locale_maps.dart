/// Shell / deals strings for all supported locales (same keys as [ukStrings]).
Map<String, String> appStringsMapForLocale(String? code) {
  switch (StartupFlowStrings.normalizeLanguageCode(code)) {
    case 'uk':
      return ukStrings;
    case 'en':
      return _enApp;
    case 'ru':
      return _ruApp;
    case 'fr':
      return _frApp;
    case 'de':
      return _deApp;
    case 'es':
      return _esApp;
    default:
      return _enApp;
  }
}

